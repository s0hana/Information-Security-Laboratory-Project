def get_bit(value, index):
    return (value >> (31 - index)) & 1

def print_mat(desc, mat, bit_len, cols):
    print(f"\n{desc}:")
    for i in range(bit_len):
        bit = (mat >> (bit_len - 1 - i)) & 1
        print(bit, end="")
        if (i + 1) % cols == 0:
            print()
        else:
            print(" ", end="")

def cipher(l0, r0, k0):
    ex_r0 = 0
    for i in range(8):
        left = get_bit(r0, (i*4 + 31) % 32)
        mid = (r0 >> (28 - i*4)) & 15
        right = get_bit(r0, (i*4 + 4) % 32)
        ex_r0 |= ((left << 5) | (mid << 1) | right) << (42 - i*6)
    print_mat("Expanded r0", ex_r0, 48, 6)
    print_mat("K0", k0, 48, 6)
    r0_k0 = ex_r0 ^ k0
    print_mat("Expanded R0 ^ K0", r0_k0, 48, 6)
    s_out = 0
    for i in range(8):
        block = (r0_k0 >> (42 - i*6)) & 63
        row = ((block >> 4) & 2) | (block & 1)
        col = (block >> 1) & 15
        s_value = s[i*64 + row*16 + col]
        s_out |= s_value << (28 - i*4)
    print_mat("S box", s_out, 32, 4)
    p_out = 0
    for i in range(32):
        p_out |= get_bit(s_out, p[i] - 1) << (31 - i)
    print_mat("Permutated s box output", p_out, 32, 8)
    print_mat("L0", l0, 32, 8)
    l1 = r0
    r1 = p_out ^ l0
    c1 = (r1 << 32) | l1
    print_mat("R1 = permutated s box ^ L0 box", r1, 32, 8)
    print(f"\nL1: {l1:08X}")
    print(f"R1: {r1:08X}")
    print(f"C1: {c1:016X}")
    return c1

